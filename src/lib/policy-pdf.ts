import PDFDocument from "pdfkit";
import { format } from "date-fns";
import type { OrderFormValue } from "@/lib/product-form";

export type PolicyPdfInput = {
  orgName?: string;
  orderNumber: number;
  policyNumber?: string | null;
  createdAt: Date;
  paymentMethod: string;
  paymentStatus: string;
  orderStatus: string;
  total: number;
  notes?: string | null;
  customer: {
    name: string;
    phone?: string | null;
    email?: string | null;
    cnic?: string | null;
    address?: string | null;
    city?: string | null;
    companyName?: string | null;
    jobTitle?: string | null;
  };
  items: {
    name: string;
    quantity: number;
    unitPrice: number;
    lineTotal: number;
    formValues: OrderFormValue[];
  }[];
};

function money(n: number) {
  return `Rs ${n.toLocaleString("en-PK", {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  })}`;
}

function paymentLabel(status: string) {
  const s = status.toUpperCase();
  if (s === "PAID" || s === "CLEARED") return `${status} — Confirmed`;
  if (s === "PARTIAL") return `${status} — Partially paid`;
  if (s === "BOUNCED" || s === "OVERDUE") return `${status} — Not confirmed`;
  return `${status} — Pending confirmation`;
}

export function buildPolicyPdfBuffer(input: PolicyPdfInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 48, size: "A4" });
    const chunks: Buffer[] = [];
    doc.on("data", (c) => chunks.push(c as Buffer));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const brand = input.orgName || "PulseCRM";

    doc
      .fontSize(18)
      .fillColor("#0f766e")
      .text(brand, { continued: false });
    doc
      .fontSize(11)
      .fillColor("#64748b")
      .text("Motor / Policy sale summary", { continued: false });
    doc.moveDown(0.6);
    doc
      .fontSize(10)
      .fillColor("#0f172a")
      .text(
        input.policyNumber
          ? `Policy #${input.policyNumber}  ·  Order #${input.orderNumber}`
          : `Order #${input.orderNumber}`,
        { continued: true }
      )
      .fillColor("#64748b")
      .text(`  ·  ${format(input.createdAt, "dd MMM yyyy, HH:mm")}`);

    doc.moveDown(1);
    section(doc, "Customer details");
    kv(doc, "Name", input.customer.name);
    kv(doc, "Phone", input.customer.phone);
    kv(doc, "Email", input.customer.email);
    kv(doc, "CNIC", input.customer.cnic);
    kv(doc, "Company", input.customer.companyName);
    kv(doc, "Designation", input.customer.jobTitle);
    kv(doc, "City", input.customer.city);
    kv(doc, "Address", input.customer.address);

    doc.moveDown(0.8);
    section(doc, "Payment status");
    kv(doc, "Method", input.paymentMethod);
    kv(doc, "Order status", input.orderStatus);
    kv(doc, "Payment", paymentLabel(input.paymentStatus));
    kv(doc, "Order total", money(input.total));
    if (input.notes) kv(doc, "Notes", input.notes);

    for (const item of input.items) {
      doc.moveDown(0.8);
      section(doc, `Policy / product — ${item.name}`);
      kv(doc, "Quantity", String(item.quantity));
      kv(doc, "Unit price", money(item.unitPrice));
      kv(doc, "Line total", money(item.lineTotal));

      if (item.formValues.length) {
        doc.moveDown(0.3);
        doc
          .fontSize(10)
          .fillColor("#0f766e")
          .text("Vehicle / form details", { underline: false });
        doc.moveDown(0.2);
        for (const f of item.formValues) {
          kv(doc, f.label, f.value);
        }
      }
    }

    doc.moveDown(1.5);
    doc
      .fontSize(8)
      .fillColor("#94a3b8")
      .text(
        "Generated by CRM · Payment confirmation may update after bank/cheque clearance.",
        { align: "left" }
      );

    doc.end();
  });
}

function section(doc: PDFKit.PDFDocument, title: string) {
  doc
    .fontSize(12)
    .fillColor("#0f172a")
    .text(title, { underline: true });
  doc.moveDown(0.35);
}

function kv(doc: PDFKit.PDFDocument, label: string, value?: string | null) {
  if (!value) return;
  doc
    .fontSize(9)
    .fillColor("#64748b")
    .text(`${label}: `, { continued: true })
    .fillColor("#0f172a")
    .text(value);
}
